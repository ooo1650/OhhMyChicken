#!/bin/sh
# Behind Cloudflare, every request reaches Nginx from a Cloudflare address, so
# all customers would share a few IPs and trip each other's rate limits.
# This writes /etc/nginx/conf.d/cloudflare-realip.conf, which tells Nginx to take
# the visitor's real IP from CF-Connecting-IP, but only when the request really
# comes from Cloudflare's published ranges (so nobody else can fake it).
# Run with sudo after enabling Cloudflare, and monthly (the ranges rarely change).
set -eu
out=/etc/nginx/conf.d/cloudflare-realip.conf
tmp=$(mktemp)
{
  echo "# Generated by deploy/nginx/cloudflare-realip.sh on $(date -u +%F). Do not edit."
  for list in ips-v4 ips-v6; do
    curl -fsS "https://www.cloudflare.com/$list" | grep -E '^[0-9a-f:.]+/[0-9]+$' | sed 's/^/set_real_ip_from /; s/$/;/'
  done
  echo "real_ip_header CF-Connecting-IP;"
} > "$tmp"
[ "$(grep -c set_real_ip_from "$tmp")" -gt 10 ] || { echo "Could not fetch Cloudflare's IP list; nothing changed." >&2; rm -f "$tmp"; exit 1; }
install -m 644 "$tmp" "$out" && rm -f "$tmp"
nginx -t && systemctl reload nginx
echo "Wrote $out ($(grep -c set_real_ip_from "$out") ranges); Nginx reloaded."
